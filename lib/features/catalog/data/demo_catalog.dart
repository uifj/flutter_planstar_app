/// 构造一条演示演出。默认城市上海、默认 3 档票、默认 2 个场次。
ShowSummary _show({
  required String id,
  required String title,
  required String artist,
  required int categoryId,
  required String categoryName,
  required String venue,
  required String venueAddress,
  required DateTime days,
  required List<(String, int)> tiers,
  String city = '上海',
  int? listPrice,
  int? discountPermille,
  List<String> tags = const <String>['电子票'],
  int wishCount = 0,
  bool soldOut = false,
  bool proxyBuy = false,
  double rating = 0,
  int ratingCount = 0,
  String duration = '约 120 分钟',
  String intro = '',
  List<String> lineup = const <String>[],
  List<String> purchaseNotice = const <String>[],
}) {
  final tierList = <TicketTier>[
    for (final (name, price) in tiers)
      TicketTier(
        name: name,
        price: Money.fromYuan(price),
        remaining: 20 + price % 60,
      ),
  ];
  final priceFrom = tierList
      .map((tier) => tier.price)
      .reduce((a, b) => a.min(b));
  final tierSummary = tierList
      .map((tier) => tier.price.minorUnits ~/ 100)
      .join('/');

  return ShowSummary(
    id: id,
    title: title,
    artist: artist,
    categoryId: categoryId,
    categoryName: categoryName,
    city: city,
    venue: venue,
    venueAddress: venueAddress,
    firstSessionAt: days,
    priceFrom: priceFrom,
    listPriceFrom: listPrice == null ? null : Money.fromYuan(listPrice),
    discountPermille: discountPermille,
    tags: tags,
    wishCount: wishCount,
    soldOut: soldOut,
    proxyBuy: proxyBuy,
    rating: rating,
    ratingCount: ratingCount,
    duration: duration,
    intro: intro,
    tiers: tierList,
    lineup: lineup,
    purchaseNotice: purchaseNotice,
    sessions: <ShowSession>[
      ShowSession(startsAt: days, tierSummary: tierSummary),
      ShowSession(
        startsAt: days.add(const Duration(days: 1)),
        tierSummary: tierSummary,
      ),
      ShowSession(
        startsAt: days.add(const Duration(days: 2)),
        tierSummary: tierSummary,
      ),
    ],
  );
}
