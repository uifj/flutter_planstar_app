/// 构造一条演示企划。
///
/// 线下活动型企划保留一个"线下回报场次"，用于验证既有选场流程；
/// 其余字段（场馆/艺人）在企划语境下分别映射为交付方式与创作者。
ShowSummary _project({
  required String id,
  required String title,
  required String creator,
  required int categoryId,
  required String categoryName,
  required int goal,
  required int raised,
  required int supporters,
  required DateTime deadline,
  required List<(String, num, String, String)> tiers,
  List<String> tags = const <String>[],
  String intro = '',
  String riskNote = '',
  String deliveryPlan = '',
  String fundUsage = '',
  String refundRule = '',
  int refundDays = 7,
  List<ProjectFaq> faqs = const <ProjectFaq>[],
  List<ProjectReview> reviews = const <ProjectReview>[],
  List<ProjectUpdate> updates = const <ProjectUpdate>[],
  String fundingStatus = 'ongoing',
  bool creatorVerified = false,
  int creatorProjectNum = 0,
  int creatorSuccessNum = 0,
  int creatorFulfillmentPermille = 0,
  String creatorBio = '',
}) {
  final tierList = <TicketTier>[
    for (final (name, price, type, items) in tiers)
      TicketTier(
        name: name,
        price: Money.fromYuan(price),
        rewardType: type,
        items: items.split('、'),
        estimatedDeliveryTime: deliveryPlan,
        remaining: fundingStatus == 'failed' ? 0 : 50,
      ),
  ];
  final priceFrom = tierList
      .map((tier) => tier.price)
      .reduce((a, b) => a.min(b));
  final tierSummary = tierList
      .map((tier) => tier.price.minorUnits ~/ 100)
      .join('/');
  final ended = fundingStatus == 'failed';
  final resolvedRefundRule = refundRule.isNotEmpty
      ? refundRule
      : (ended
            ? '企划未达成，支持金额已按原支付渠道全额退回，预计 $refundDays 天内到账。'
            : '未达成：支持金额原路全额退回，平台不收手续费；达成后除回报质量问题外不支持无理由退款。');
  final resolvedFaqs = faqs.isNotEmpty
      ? faqs
      : <ProjectFaq>[
          ProjectFaq(question: '支持后可以退款吗？', answer: resolvedRefundRule),
          ProjectFaq(
            question: '回报什么时候交付？',
            answer: deliveryPlan.isEmpty ? '以企划页的进度更新为准。' : deliveryPlan,
          ),
          ProjectFaq(
            question: '怎样查看进度和回报？',
            answer: '在「我的支持」中查看进度更新、物流单号或权益核销码。',
          ),
        ];
  final resolvedReviews = reviews.isNotEmpty
      ? reviews
      : _demoReviews(id, fundingStatus, deadline);

  return ShowSummary(
    id: id,
    title: title,
    artist: creator,
    categoryId: categoryId,
    categoryName: categoryName,
    city: '上海',
    venue: '线上企划',
    venueAddress: '达成后按回报档位交付',
    firstSessionAt: deadline,
    priceFrom: priceFrom,
    tags: tags,
    wishCount: supporters,
    soldOut: ended,
    rating: 0,
    ratingCount: 0,
    duration: deliveryPlan,
    intro: intro,
    tiers: tierList,
    lineup: <String>[creator],
    purchaseNotice: <String>['支持成功后可在「我的支持」查看回报与进度。', '企划未达成时，按规则原路退款。'],
    sessions: <ShowSession>[
      ShowSession(startsAt: deadline, tierSummary: tierSummary),
    ],
    goalAmount: Money.fromYuan(goal.toDouble()),
    raisedAmount: Money.fromYuan(raised.toDouble()),
    supporterCount: supporters,
    deadline: deadline,
    fundingStatus: fundingStatus,
    riskNote: riskNote,
    deliveryPlan: deliveryPlan,
    fundUsage: fundUsage,
    refundRule: resolvedRefundRule,
    refundDays: refundDays,
    faqs: resolvedFaqs,
    reviews: resolvedReviews,
    updates: updates,
    creatorVerified: creatorVerified,
    creatorProjectNum: creatorProjectNum,
    creatorSuccessNum: creatorSuccessNum,
    creatorFulfillmentPermille: creatorFulfillmentPermille,
    creatorBio: creatorBio,
  );
}

