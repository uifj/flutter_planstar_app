/// 已交付企划的默认评价样本。
///
/// 契约要求「发布评价的 `pledgeId` 必须已交付」，因此 `ongoing` / `achieved`
/// （筹资中或履约中）都不生成评价，避免出现「未交付却已有晒单」的脏数据。
List<ProjectReview> _demoReviews(
  String id,
  String fundingStatus,
  DateTime deadline,
) {
  if (fundingStatus != 'delivered') {
    return const <ProjectReview>[];
  }
  final seed = int.tryParse(id) ?? 0;
  final name = _reviewerNames[seed % _reviewerNames.length];
  final secondName = _reviewerNames[(seed + 5) % _reviewerNames.length];
  return <ProjectReview>[
    ProjectReview(
      userName: name,
      rating: 5,
      content: '实物和描述一致，包装扎实，开箱体验很好。',
      isShow: true,
      likeCount: 20 + seed % 40,
      createdAt: deadline.add(const Duration(days: 30)),
    ),
    ProjectReview(
      userName: secondName,
      rating: 4,
      content: '数字内容发放很及时，附赠内容比预期多。',
      likeCount: 8 + seed % 20,
      createdAt: deadline.add(const Duration(days: 45)),
    ),
    ProjectReview(
      userName: '匿名支持者',
      rating: 5,
      content: '进度更新透明，交付比预计还早一点。',
      isAnonymous: true,
      likeCount: 5 + seed % 10,
      createdAt: deadline.add(const Duration(days: 60)),
    ),
  ];
}
